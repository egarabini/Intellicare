def simplify_term(term: str) -> str:
    """
    Busca termo no glossário e retorna tradução.

    Args:
        term: Termo médico a simplificar

    Returns:
        Tradução em linguagem leiga ou termo original se não encontrado
    """
    term_normalized = term.lower().strip()
    return MEDICAL_GLOSSARY.get(term_normalized, term)


def has_translation(term: str) -> bool:
    """
    Verifica se termo tem tradução no glossário.

    Args:
        term: Termo médico

    Returns:
        True se tem tradução, False caso contrário
    """
    term_normalized = term.lower().strip()
    return term_normalized in MEDICAL_GLOSSARY


def get_all_terms() -> list[str]:
    """
    Retorna lista de todos os termos do glossário.

    Returns:
        Lista de termos médicos
    """
    return list(MEDICAL_GLOSSARY.keys())
